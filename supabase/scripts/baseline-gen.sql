set search_path to pg_catalog;
with
ns as (select 'public'::regnamespace::oid as oid),
tbl as (
  select c.oid, c.relname, c.relkind, c.relrowsecurity, c.relforcerowsecurity, c.relowner, c.relacl
  from pg_class c where c.relnamespace = (select oid from ns) and c.relkind in ('r', 'p')
),
latetype as (
  select ty.oid from pg_type ty left join pg_type el on el.oid = ty.typelem
  where ty.typrelid <> 0 or ty.typtype = 'd' or coalesce(el.typrelid, 0) <> 0 or el.typtype = 'd'
),
fn as (
  select p.oid, p.proname, p.prokind, p.proowner, p.proacl,
    (p.prosqlbody is not null
      or p.prorettype in (select oid from latetype)
      or exists (select 1 from unnest(coalesce(p.proallargtypes, p.proargtypes::oid[])) a(t) where a.t in (select oid from latetype))
    ) as late
  from pg_proc p
  where p.pronamespace = (select oid from ns)
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
),
out(sec, ord, ddl) as (
  -- roles created for this project (not part of a fresh Supabase project)
  select 10, r.rolname::text, format('do $r$ begin if not exists (select 1 from pg_roles where rolname = %L) then create role %I %s; end if; end $r$;',
      r.rolname, r.rolname,
      concat_ws(' ', case when r.rolcanlogin then 'login' else 'nologin' end,
                     case when r.rolbypassrls then 'bypassrls' else 'nobypassrls' end,
                     case when r.rolinherit then 'inherit' else 'noinherit' end))
  from pg_roles r where r.rolname = 'washup_vendor_panel'
  union all
  select 11, r.rolname || '>' || m.member::regrole::text, format('grant %I to %I;', r.rolname, m.member::regrole::text)
  from pg_auth_members m join pg_roles r on r.oid = m.roleid where r.rolname = 'washup_vendor_panel'
  union all
  -- extensions
  select 20, e.extname::text, format('create extension if not exists %I with schema %I;', e.extname, e.extnamespace::regnamespace::text)
  from pg_extension e where e.extname <> 'plpgsql'
  union all
  -- enums
  select 30, t.typname::text, format('create type public.%I as enum (%s);', t.typname,
      (select string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder) from pg_enum e where e.enumtypid = t.oid))
  from pg_type t where t.typnamespace = (select oid from ns) and t.typtype = 'e'
  union all
  -- functions whose signature needs no table / domain type
  select 35, f.oid::regprocedure::text, pg_get_functiondef(f.oid) || ';'
  from fn f where not f.late and f.prokind <> 'a'
  union all
  -- domains
  select 36, t.typname::text, format('create domain public.%I as %s%s%s%s;', t.typname, format_type(t.typbasetype, t.typtypmod),
      case when t.typdefault is not null then ' default ' || t.typdefault else '' end,
      case when t.typnotnull then ' not null' else '' end,
      coalesce((select string_agg(' constraint ' || quote_ident(c.conname) || ' ' || pg_get_constraintdef(c.oid), '' order by c.conname)
                from pg_constraint c where c.contypid = t.oid), ''))
  from pg_type t where t.typnamespace = (select oid from ns) and t.typtype = 'd'
  union all
  -- composite types
  select 37, t.typname::text, format('create type public.%I as (%s);', t.typname,
      (select string_agg(quote_ident(a.attname) || ' ' || format_type(a.atttypid, a.atttypmod), ', ' order by a.attnum)
       from pg_attribute a where a.attrelid = t.typrelid and a.attnum > 0 and not a.attisdropped))
  from pg_type t join pg_class c on c.oid = t.typrelid
  where t.typnamespace = (select oid from ns) and t.typtype = 'c' and c.relkind = 'c'
  union all
  -- sequences (identity sequences come with their column)
  select 40, c.relname::text, format('create sequence if not exists public.%I as %s increment by %s minvalue %s maxvalue %s start with %s cache %s%s;',
      c.relname, format_type(s.seqtypid, null), s.seqincrement, s.seqmin, s.seqmax, s.seqstart, s.seqcache,
      case when s.seqcycle then ' cycle' else '' end)
  from pg_class c join pg_sequence s on s.seqrelid = c.oid
  where c.relnamespace = (select oid from ns) and c.relkind = 'S'
    and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'i')
  union all
  -- tables
  select 50, t.relname::text, format('create table public.%I (%s%s%s)%s;', t.relname, chr(10) || '  ',
      (select string_agg(format('%I %s%s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
           case when a.attcollation <> 0 and a.attcollation <> ty.typcollation
                then ' collate ' || (select quote_ident(collname) from pg_collation where oid = a.attcollation) else '' end,
           case when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(ad.adbin, ad.adrelid) || ') stored'
                when a.attidentity = 'a' then ' generated always as identity'
                when a.attidentity = 'd' then ' generated by default as identity'
                when ad.adbin is not null then ' default ' || pg_get_expr(ad.adbin, ad.adrelid) else '' end,
           case when a.attnotnull then ' not null' else '' end), ',' || chr(10) || '  ' order by a.attnum)
       from pg_attribute a join pg_type ty on ty.oid = a.atttypid
       left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
       where a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped),
      chr(10),
      case when t.relkind = 'p' then ' partition by ' || pg_get_partkeydef(t.oid) else '' end)
  from tbl t
  union all
  select 55, c.relname::text, format('alter sequence public.%I owned by public.%I.%I;', c.relname, t.relname, a.attname)
  from pg_depend d join pg_class c on c.oid = d.objid and c.relkind = 'S'
  join pg_class t on t.oid = d.refobjid join pg_attribute a on a.attrelid = t.oid and a.attnum = d.refobjsubid
  where d.deptype = 'a' and d.classid = 'pg_class'::regclass and c.relnamespace = (select oid from ns)
  union all
  -- primary keys, unique, check, exclusion
  select 60, t.relname || '.' || co.contype::text || '.' || co.conname,
      format('alter table only public.%I add constraint %I %s;', t.relname, co.conname, pg_get_constraintdef(co.oid))
  from pg_constraint co join tbl t on t.oid = co.conrelid where co.contype in ('p', 'u', 'c', 'x')
  union all
  -- other indexes
  select 70, t.relname || '.' || i.relname, pg_get_indexdef(i.oid) || ';'
  from pg_index x join pg_class i on i.oid = x.indexrelid join tbl t on t.oid = x.indrelid
  where not exists (select 1 from pg_constraint co where co.conindid = i.oid and co.conrelid = t.oid and co.contype in ('p', 'u', 'x'))
  union all
  -- views
  select 80, c.relname::text, format('create %sview public.%I%s as%s%s', case when c.relkind = 'm' then 'materialized ' else '' end, c.relname,
      case when c.reloptions is not null then ' with (' || array_to_string(c.reloptions, ', ') || ')' else '' end, chr(10), pg_get_viewdef(c.oid))
  from pg_class c where c.relnamespace = (select oid from ns) and c.relkind in ('v', 'm')
  union all
  -- functions that need table / domain types
  select 85, f.oid::regprocedure::text, pg_get_functiondef(f.oid) || ';'
  from fn f where f.late and f.prokind <> 'a'
  union all
  -- foreign keys
  select 90, t.relname || '.' || co.conname,
      format('alter table only public.%I add constraint %I %s;', t.relname, co.conname, pg_get_constraintdef(co.oid))
  from pg_constraint co join tbl t on t.oid = co.conrelid where co.contype = 'f'
  union all
  -- triggers on public tables, and triggers elsewhere that call public functions
  select 100, c.relnamespace::regnamespace || '.' || c.relname || '.' || tg.tgname,
      pg_get_triggerdef(tg.oid) || ';' ||
      case when tg.tgenabled = 'D' then chr(10) || format('alter table %s disable trigger %I;', c.oid::regclass, tg.tgname) else '' end
  from pg_trigger tg join pg_class c on c.oid = tg.tgrelid join pg_proc p on p.oid = tg.tgfoid
  where not tg.tgisinternal and (c.relnamespace = (select oid from ns) or p.pronamespace = (select oid from ns))
  union all
  -- row level security
  select 110, relname::text, format('alter table public.%I enable row level security;', relname) ||
      case when relforcerowsecurity then format(' alter table public.%I force row level security;', relname) else '' end
  from tbl where relrowsecurity
  union all
  select 120, po.tablename || '.' || po.policyname,
      format('create policy %I on public.%I as %s for %s to %s%s%s;', po.policyname, po.tablename, lower(po.permissive), lower(po.cmd),
        (select string_agg(case when r = 'public' then 'public' else quote_ident(r) end, ', ') from unnest(po.roles) r),
        case when po.qual is not null then chr(10) || '  using (' || po.qual || ')' else '' end,
        case when po.with_check is not null then chr(10) || '  with check (' || po.with_check || ')' else '' end)
  from pg_policies po where po.schemaname = 'public'
  union all
  -- comments
  select 130, c.relname::text, format('comment on %s public.%I is %L;', case when c.relkind in ('v', 'm') then 'view' else 'table' end, c.relname, d.description)
  from pg_description d join pg_class c on c.oid = d.objoid
  where d.classoid = 'pg_class'::regclass and d.objsubid = 0 and c.relnamespace = (select oid from ns) and c.relkind in ('r', 'p', 'v', 'm')
  union all
  select 131, c.relname || '.' || a.attname, format('comment on column public.%I.%I is %L;', c.relname, a.attname, d.description)
  from pg_description d join pg_class c on c.oid = d.objoid join pg_attribute a on a.attrelid = c.oid and a.attnum = d.objsubid
  where d.classoid = 'pg_class'::regclass and d.objsubid > 0 and c.relnamespace = (select oid from ns)
  union all
  select 132, f.oid::regprocedure::text, format('comment on function %s is %L;', f.oid::regprocedure, d.description)
  from pg_description d join fn f on f.oid = d.objoid where d.classoid = 'pg_proc'::regclass
  union all
  select 133, t.typname::text, format('comment on type public.%I is %L;', t.typname, d.description)
  from pg_description d join pg_type t on t.oid = d.objoid where d.classoid = 'pg_type'::regclass and t.typnamespace = (select oid from ns)
  union all
  -- privileges: reset what a fresh project grants by default, then grant exactly what is live
  select 140, n.nspname || '>' || pg_get_userbyid(a.grantee), format('grant %s on schema public to %I;', string_agg(lower(a.privilege_type), ', ' order by a.privilege_type), pg_get_userbyid(a.grantee))
  from pg_namespace n, aclexplode(n.nspacl) a
  where n.oid = (select oid from ns) and pg_get_userbyid(a.grantee) not in ('pg_database_owner', 'postgres', 'anon', 'authenticated', 'service_role') and a.grantee <> 0
  group by n.nspname, a.grantee
  union all
  select 141, c.relname::text, format('revoke all on %s public.%I from public, anon, authenticated, service_role, washup_vendor_panel;',
      case when c.relkind = 'S' then 'sequence' else 'table' end, c.relname)
  from pg_class c where c.relnamespace = (select oid from ns) and c.relkind in ('r', 'p', 'v', 'm', 'S')
  union all
  select 142, c.relname || '>' || a.grantee, format('grant %s on %s public.%I to %s;', string_agg(lower(a.privilege_type), ', ' order by a.privilege_type),
      case when c.relkind = 'S' then 'sequence' else 'table' end, c.relname,
      case when a.grantee = 0 then 'public' else quote_ident(pg_get_userbyid(a.grantee)) end)
  from pg_class c, aclexplode(coalesce(c.relacl, acldefault((case when c.relkind = 'S' then 's' else 'r' end)::"char", c.relowner))) a
  where c.relnamespace = (select oid from ns) and c.relkind in ('r', 'p', 'v', 'm', 'S') and a.grantee <> c.relowner
  group by c.relname, c.relkind, a.grantee
  union all
  select 143, c.relname || '>' || g.grantee || '>' || g.priv, format('grant %s (%s) on table public.%I to %s;', g.priv,
      string_agg(quote_ident(g.attname), ', ' order by g.attnum), c.relname,
      case when g.grantee = 0 then 'public' else quote_ident(pg_get_userbyid(g.grantee)) end)
  from pg_class c cross join lateral (
      select a.attname, a.attnum, x.grantee, lower(x.privilege_type) priv
      from pg_attribute a, aclexplode(a.attacl) x where a.attrelid = c.oid and a.attacl is not null and a.attnum > 0 and not a.attisdropped) g
  where c.relnamespace = (select oid from ns) and c.relkind in ('r', 'p', 'v', 'm')
  group by c.relname, g.grantee, g.priv
  union all
  select 144, f.oid::regprocedure::text, format('revoke all on function %s from public, anon, authenticated, service_role, washup_vendor_panel;', f.oid::regprocedure)
  from fn f where f.prokind <> 'a'
  union all
  select 145, f.oid::regprocedure || '>' || a.grantee, format('grant execute on function %s to %s;', f.oid::regprocedure,
      case when a.grantee = 0 then 'public' else quote_ident(pg_get_userbyid(a.grantee)) end)
  from fn f, aclexplode(coalesce(f.proacl, acldefault('f', f.proowner))) a
  where f.prokind <> 'a' and a.grantee <> f.proowner
  union all
  -- realtime
  select 150, pt.tablename::text, format('do $x$ begin if not exists (select 1 from pg_publication_tables where pubname = %L and schemaname = %L and tablename = %L) then alter publication %I add table public.%I; end if; end $x$;',
      pt.pubname, 'public', pt.tablename, pt.pubname, pt.tablename)
  from pg_publication_tables pt where pt.pubname = 'supabase_realtime' and pt.schemaname = 'public'
  union all
  -- scheduled jobs
  select 160, j.jobname::text, format('select cron.schedule(%L, %L, %L);', j.jobname, j.schedule, j.command) from cron.job j
  union all
  -- storage buckets (definitions only, no files)
  select 170, b.id::text, format('insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types) values (%L, %L, %s, %s, %L) on conflict (id) do nothing;',
      b.id, b.name, case when b.public then 'true' else 'false' end, coalesce(b.file_size_limit::text, 'null'), b.allowed_mime_types)
  from storage.buckets b
)
select sec, count(*) n, sum(length(ddl)) bytes, json_agg(ddl order by ord) ddl from out group by sec order by sec;
